// 週ごとに順番に切り替える(2026年1月5日の週を起点に、6テーマを順に回す)
export function pickTheme(thisMon: string): SlideTheme {
  const base = Date.parse("2026-01-05T00:00:00Z");
  const t = Date.parse(thisMon + "T00:00:00Z");
  const weeks = Math.floor((t - base) / (7 * 86400000));
  const idx = ((weeks % THEMES.length) + THEMES.length) % THEMES.length;
  return THEMES[idx];
}
